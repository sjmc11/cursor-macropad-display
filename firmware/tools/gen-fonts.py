#!/usr/bin/env python3
"""Render Inter into 4-bit anti-aliased bitmap fonts (ASCII 32-126) as a C header."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # (c name, path, pixel size)
    ("font_s", "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf", 15),
    ("font_m", "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf", 20),
    ("font_l", "/usr/share/fonts/opentype/inter/Inter-Bold.otf", 30),
]

out = ["// Generated by tools/gen-fonts.py from Inter (SIL Open Font License). Do not edit.",
       "#pragma once", "#include <stdint.h>", "",
       "typedef struct { uint16_t offset; uint8_t w, h; int8_t x, y; uint8_t adv; } glyph_t;",
       "typedef struct { const uint8_t *bits; const glyph_t *glyphs; uint8_t height, ascent; } font_t;", ""]
for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    ascent, descent = f.getmetrics()
    height = ascent + descent
    bits = bytearray()
    glyphs = []
    for c in range(32, 127):
        ch = chr(c)
        adv = round(f.getlength(ch))
        bbox = f.getbbox(ch)  # relative to origin at top (ascent line)
        if bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            glyphs.append((len(bits), 0, 0, 0, 0, adv)); continue
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=f, fill=255)
        px = list(img.getdata())
        off = len(bits)
        nib = [p >> 4 for p in px]
        if len(nib) % 2: nib.append(0)
        for i in range(0, len(nib), 2):
            bits.append((nib[i] << 4) | nib[i + 1])
        glyphs.append((off, w, h, bbox[0], bbox[1], adv))
    out.append(f"static const uint8_t {name}_bits[{len(bits)}] = {{")
    for i in range(0, len(bits), 24):
        out.append("  " + ",".join(f"0x{b:02x}" for b in bits[i:i+24]) + ",")
    out.append("};")
    out.append(f"static const glyph_t {name}_glyphs[95] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const font_t {name} = {{ {name}_bits, {name}_glyphs, {height}, {ascent} }};")
    out.append("")
    print(name, size, "height", height, "bytes", len(bits), file=sys.stderr)
open(sys.argv[1], "w").write("\n".join(out) + "\n")
