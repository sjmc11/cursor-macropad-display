// Generates keybindings JSON and the mapping-sheet markdown.
// Pure functions — no file I/O, works in both Node and browser.

import { DeviceConfig, Config, Action } from './types';
import { allInputs, keys, knobs } from './scheme';

export interface KeyBinding { key: string; command: string; args: string }

export function generateKeybindings(device: DeviceConfig): KeyBinding[] {
  return allInputs(device)
    .filter((i) => !device.appOnly[i.inputId])
    .map((i) => ({ key: i.combo, command: 'macropad.input', args: i.inputId }));
}

export function generateMappingDoc(device: DeviceConfig, cfg: Config): string {
  const inputs = allInputs(device);
  const label = (id: string): string => device.appOnly[id] ?? (cfg.inputs?.[id] as Action | undefined)?.label ?? '—';

  let md = `# Mini_Keyboard app mapping\n\n`;
  md += `Generated by Macropad Studio — don't edit by hand.\n\n`;
  md += `| Layer | Modifier | Cursor sees |\n|---|---|---|\n`;
  for (const l of device.layers) md += `| ${l.n} · ${l.name} | \`${l.app}\` | \`${l.vscode}+…\` |\n`;

  for (const l of device.layers) {
    md += `\n## Layer ${l.n} · ${l.name}\n\n### Keys (physical layout, knobs at the bottom)\n\n| | Left | Middle | Right |\n|---|---|---|---|\n`;
    device.physicalRows.forEach((row, r) => {
      md += `| Row ${r + 1} | ` + row.map((n) => {
        const k = keys[n - 1];
        return `**${label(`L${l.n}.${k.id}`)}**<br>app key ${n} → \`${l.app} ${k.letter.toUpperCase()}\``;
      }).join(' | ') + ' |\n';
    });
    md += `\n### Knobs\n\n| Knob (physical) | App knob | Turn left | Turn right | Press |\n|---|---|---|---|---|\n`;
    for (const kn of knobs) {
      const cells = (['left', 'right', 'press'] as const).map((dir) => {
        const inp = inputs.find((i) => i.inputId === `L${l.n}.${kn.id}.${dir}`)!;
        if (device.appOnly[inp.inputId]) return `**${device.appOnly[inp.inputId]}**<br>MultiMedia tab`;
        return `**${label(inp.inputId)}**<br>\`${inp.app}\``;
      });
      md += `| ${kn.physical} | ${kn.appKnob} | ${cells.join(' | ')} |\n`;
    }
  }
  return md;
}
